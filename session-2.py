# Sum of two floating point numbers
float1 = 10.5
float2 = 3.2
float_sum = float1 + float2
print(f"Sum of {float1} and {float2}: {float_sum}, Type: {type(float_sum)}")

# Difference between two integers
int1 = 25
int2 = 7
int_difference = int1 - int2
print(f"Difference between {int1} and {int2}: {int_difference}, Type: {type(int_difference)}")

# Product of a floating point number and an integer
float_num = 4.0
int_num = 6
product = float_num * int_num
print(f"Product of {float_num} and {int_num}: {product}, Type: {type(product)}")